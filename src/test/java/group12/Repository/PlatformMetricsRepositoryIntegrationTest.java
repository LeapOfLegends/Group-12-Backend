package group12.Repository;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.math.BigDecimal;
import java.time.Instant;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;

@Testcontainers(disabledWithoutDocker = true)
class PlatformMetricsRepositoryIntegrationTest {

    @Container
    static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:18-alpine");

    private PlatformMetricsRepository repository;

    @BeforeEach
    void setUp() {
        var datasource = new DriverManagerDataSource(POSTGRES.getJdbcUrl(), POSTGRES.getUsername(), POSTGRES.getPassword());
        var jdbc = new JdbcTemplate(datasource);
        repository = new PlatformMetricsRepository(new NamedParameterJdbcTemplate(datasource));
        jdbc.execute("CREATE SCHEMA IF NOT EXISTS dw");
        jdbc.execute("DROP TABLE IF EXISTS dw.table_records");
        jdbc.execute("""
                CREATE TABLE dw.table_records (
                    client_id bigint GENERATED BY DEFAULT AS IDENTITY, instrument_id bigint DEFAULT 1,
                    created_at timestamptz DEFAULT '2026-10-23T00:00:00Z',
                    accepted_at timestamptz, failed_at timestamptz, rejected_at timestamptz,
                    currency text, submitted_at timestamptz, filled_at timestamptz,
                    order_status text, trade_value numeric(18,4)
                )
                """);
        jdbc.execute("""
                INSERT INTO dw.table_records (currency, submitted_at, filled_at, order_status, trade_value) VALUES
                    ('USD', '2026-10-16T12:00:00Z', '2026-10-17T12:00:00Z', 'FILLED', 100.25),
                    ('USD', '2026-10-15T12:00:00Z', '2026-10-18T12:00:00Z', 'FILLED', 200.50),
                    ('GBP', '2026-10-20T12:00:00Z', '2026-10-21T12:00:00Z', 'FILLED', 50.00),
                    ('USD', '2026-10-20T12:00:00Z', null, 'ACCEPTED', null),
                    ('USD', '2026-10-20T12:00:00Z', null, 'SUBMITTED', null),
                    ('USD', '2026-10-20T12:00:00Z', null, 'FAILED', null),
                    ('USD', '2026-10-20T12:00:00Z', null, 'REJECTED', null),
                    ('USD', '2026-10-23T12:00:00Z', '2026-10-23T12:00:00Z', 'FILLED', 999),
                    ('USD', '2025-01-01T12:00:00Z', '2025-01-01T12:00:00Z', 'FILLED', 10)
                """);
                jdbc.execute("""
                    INSERT INTO dw.table_records (instrument_id, created_at, currency, submitted_at, filled_at, order_status, trade_value)
                    SELECT instrument_id, created_at, currency, submitted_at, filled_at, order_status, trade_value
                    FROM dw.table_records WHERE client_id = 1
                    """);
                jdbc.execute("UPDATE dw.table_records SET client_id = 1 WHERE client_id = 10");
    }

    @Test
    void countsSubmissionCohortsAndValuesFillsWithoutMixingCurrencies() {
        var rows = repository.summarize(Instant.parse("2026-10-16T12:00:00Z"), Instant.parse("2026-10-23T12:00:00Z"));
        assertEquals(2, rows.size());
        var usd = rows.stream().filter(row -> row.currency().equals("USD")).findFirst().orElseThrow();
        assertEquals(5, usd.totalOrders());
        assertEquals(2, usd.filledOrders());
        assertEquals(2, usd.pendingOrders());
        assertEquals(2, usd.failedRejectedOrders());
        assertEquals(0, new BigDecimal("300.75").compareTo(usd.tradingValue()));
        assertEquals("GBP", rows.getFirst().currency());
        assertEquals(0, new BigDecimal("50").compareTo(rows.getFirst().tradingValue()));
    }

    @Test
    void allTimeHasNoLowerBoundButExcludesFutureRecords() {
        var rows = repository.summarize(null, Instant.parse("2026-10-23T12:00:00Z"));
        assertEquals(8, rows.stream().mapToLong(PlatformMetricsRepository.CurrencyMetrics::totalOrders).sum());
    }

    @Test
    void noMatchingRowsReturnsEmptySummary() {
        assertEquals(0, repository.summarize(Instant.parse("2027-01-01T00:00:00Z"), Instant.parse("2027-02-01T00:00:00Z")).size());
    }
}